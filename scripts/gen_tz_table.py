#!/usr/bin/env python3
"""Generate include/wb_tz_table.h: IANA timezone name -> POSIX TZ string (#81).

The charger reports its timezone as an IANA name (g_tzn), but newlib's
tzset() only understands POSIX TZ strings and the ESP32 has no tz database.
Every TZif v2+ file ends with a POSIX TZ footer describing the zone's rule
after its last explicit transition. This reads that footer for every zone in
a system zoneinfo tree, adds the backward links listed in tzdata.zi (e.g.
Europe/Kiev -> Europe/Kyiv, so the output doesn't depend on tzdata-legacy
being installed), and checks each string against the zone's real offsets for
the next two years, dropping any that disagree.

Usage: python3 scripts/gen_tz_table.py [/usr/share/zoneinfo] [include/wb_tz_table.h]
"""
import os
import re
import sys
import time
from datetime import datetime, timezone
from zoneinfo import ZoneInfo

ZONEINFO = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(__file__), "..", "include", "wb_tz_table.h")

# Top-level areas of the canonical names; skips posix/, right/, Etc/ aliases
# like "GMT+3" (the charger doesn't use them) and the legacy US/, Canada/ ...
AREAS = ("Africa", "America", "Antarctica", "Arctic", "Asia", "Atlantic",
         "Australia", "Europe", "Indian", "Pacific")
CHECK_DAYS = 2 * 366
CHECK_STEP = 15 * 60


def footer(path):
    """POSIX TZ footer of a TZif v2+ file, or None (v1 file or empty footer)."""
    with open(path, "rb") as f:
        data = f.read()
    if not data.startswith(b"TZif") or data[4:5] < b"2" or not data.endswith(b"\n"):
        return None
    start = data.rfind(b"\n", 0, len(data) - 1)
    tz = data[start + 1:-1].decode("ascii") if start >= 0 else ""
    return tz or None


def tzdata_zi():
    try:
        with open(os.path.join(ZONEINFO, "tzdata.zi")) as f:
            return f.read().splitlines()
    except OSError:
        return []


def version(lines):
    m = re.match(r"# version (\S+)", lines[0]) if lines else None
    return m.group(1) if m else "unknown"


CHECK_FROM = int(time.time()) // 86400 * 86400
CHECK_TO = CHECK_FROM + CHECK_DAYS * 86400


def day(t):
    return datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d")


def mismatch(posix, zone):
    """First instant in [CHECK_FROM, CHECK_TO) where posix and zoneinfo disagree."""
    os.environ["TZ"] = posix
    time.tzset()
    z = ZoneInfo(zone)
    for t in range(CHECK_FROM, CHECK_TO, CHECK_STEP):
        want = datetime.fromtimestamp(t, z).utcoffset().total_seconds()
        if time.localtime(t).tm_gmtoff != want:
            return t
    return None


def in_areas(name):
    return name.split("/", 1)[0] in AREAS


lines = tzdata_zi()
# name -> canonical zone whose TZif file we read
sources = {}
for area in AREAS:
    for root, _, files in os.walk(os.path.join(ZONEINFO, area)):
        for name in files:
            rel = os.path.relpath(os.path.join(root, name), ZONEINFO)
            sources[rel] = rel
for line in lines:
    parts = line.split()
    if len(parts) == 3 and parts[0] == "L" and in_areas(parts[2]):
        sources.setdefault(parts[2], parts[1])

rows = {"UTC": "UTC0"}
skipped = []
for name, src in sorted(sources.items()):
    path = os.path.join(ZONEINFO, src)
    if not os.path.isfile(path):
        skipped.append(name + " (target missing)")
        continue
    tz = footer(path)
    if not tz:
        skipped.append(name + " (no footer)")
        continue
    # newlib reads the "/time" of a DST rule with %hu, so a negative transition
    # time (RFC 8536 extension, e.g. America/Nuuk "M3.5.0/-1") would be
    # misparsed as ~65535 h. Leave those out: an unknown name falls back to
    # UTC. Hours above 24 (Asia/Jerusalem "/26") are fine.
    if re.search(r"/-", tz):
        skipped.append(name + " (negative rule time)")
        continue
    # The footer only describes the rule after the last explicit transition,
    # which may still be in the future (e.g. a zone changing its rules).
    bad = mismatch(tz, src)
    if bad is not None:
        skipped.append("%s (footer wrong on %s)" % (name, day(bad)))
        continue
    rows[name] = tz

names = sorted(rows)
with open(OUT, "w") as f:
    f.write("// GENERATED by scripts/gen_tz_table.py from tzdata %s, checked %s..%s - do not edit.\n"
            % (version(lines), day(CHECK_FROM), day(CHECK_TO - 1)))
    f.write("// IANA timezone name -> POSIX TZ string, sorted by name (binary search).\n")
    f.write("#pragma once\n\n")
    f.write("struct WbTzEntry { const char* name; const char* posix; };\n\n")
    f.write("static const WbTzEntry kWbTzTable[] = {\n")
    for n in names:
        f.write('    {"%s", "%s"},\n' % (n, rows[n]))
    f.write("};\n")
    f.write("static const unsigned kWbTzTableCount = %d;\n" % len(names))
print("%d zones -> %s" % (len(names), OUT))
for s in skipped:
    print("  skipped:", s)
